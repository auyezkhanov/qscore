import { Link } from "react-router-dom";
import { CalendarClock, Lightbulb, TrendingUp } from "lucide-react";
import type { FormEntry, MatchPreview, MatchSummary, TeamRef } from "@/shared/api/types";
import { useI18n } from "@/shared/i18n/LanguageProvider";
import type { TranslationKey } from "@/shared/i18n/ru";
import { formatDate, formatTime } from "@/shared/lib/date";
import { cn } from "@/shared/lib/utils";
import { CardHeader } from "@/shared/ui/Card";
import { FormBadge } from "@/shared/ui/FormBadge";
import { TeamLogo } from "@/shared/ui/TeamLogo";

// ---------- form ----------

/** Last five results of both clubs, oldest → newest, each linking to its match. */
export function FormCard({ preview }: { preview: MatchPreview }) {
  const { t } = useI18n();
  const { form, teams } = preview;
  if (form.home.length === 0 && form.away.length === 0) return null;

  return (
    <section className="card overflow-hidden">
      <CardHeader title={t("preview.form")} icon={<TrendingUp size={16} />} />
      <div className="grid grid-cols-1 divide-y divide-line sm:grid-cols-2 sm:divide-x sm:divide-y-0">
        <FormSide team={teams.home} entries={form.home} />
        <FormSide team={teams.away} entries={form.away} />
      </div>
    </section>
  );
}

function FormSide({ team, entries }: { team: TeamRef; entries: FormEntry[] }) {
  const { t } = useI18n();
  const ordered = [...entries].sort((a, b) => a.match.kickoff.localeCompare(b.match.kickoff));

  return (
    <div className="px-4 py-3.5 sm:px-5">
      <Link to={`/team/${team.slug}`} className="mb-3 flex min-w-0 items-center gap-2 text-sm font-bold hover:underline">
        <TeamLogo team={team} size="sm" />
        <span className="truncate">{team.name}</span>
      </Link>
      {ordered.length === 0 ? (
        <p className="text-xs text-ink-3">{t("common.noData")}</p>
      ) : (
        <ol className="grid grid-cols-5 gap-1.5">
          {ordered.map(({ match: m, result }) => {
            const home = m.homeTeam.id === team.id;
            const opponent = home ? m.awayTeam : m.homeTeam;
            const gf = home ? m.homeScore : m.awayScore;
            const ga = home ? m.awayScore : m.homeScore;
            return (
              <li key={m.id}>
                <Link
                  to={`/match/${m.id}`}
                  title={`${m.homeTeam.name} ${m.homeScore ?? ""}–${m.awayScore ?? ""} ${m.awayTeam.name}`}
                  className="flex flex-col items-center gap-1.5 rounded-lg py-1 transition-colors hover:bg-surface-2"
                >
                  <FormBadge result={result} label={gf != null && ga != null ? `${gf}-${ga}` : undefined} className="h-6 w-full max-w-[3rem] text-xs" />
                  <TeamLogo team={opponent} size="sm" />
                  <span className="sr-only">{opponent.name}</span>
                </Link>
              </li>
            );
          })}
        </ol>
      )}
    </div>
  );
}

// ---------- facts ----------

const FACT_KEYS: Record<string, TranslationKey> = {
  winStreak: "fact.winStreak",
  loseStreak: "fact.loseStreak",
  unbeaten: "fact.unbeaten",
  winless: "fact.winless",
  scoredLast5: "fact.scoredLast5",
  cleanSheetsLast5: "fact.cleanSheetsLast5",
  bestHome: "fact.bestHome",
  bestAway: "fact.bestAway",
  worstHome: "fact.worstHome",
  leagueTopScorer: "fact.leagueTopScorer",
  teamTopScorer: "fact.teamTopScorer",
  h2hWinStreak: "fact.h2hWinStreak",
  h2hGoals: "fact.h2hGoals",
};

/** Pre-match talking points generated by the API; unknown fact keys are skipped. */
export function FactsCard({ preview }: { preview: MatchPreview }) {
  const { t } = useI18n();
  const facts = preview.facts.filter((f) => f.key in FACT_KEYS);
  if (facts.length === 0) return null;

  return (
    <section className="card overflow-hidden">
      <CardHeader title={t("preview.facts")} icon={<Lightbulb size={16} />} />
      <ul className="divide-y divide-line">
        {facts.map((f, i) => {
          const team = f.side ? preview.teams[f.side] : null;
          return (
            <li key={`${f.key}:${f.side ?? "both"}:${i}`} className="flex items-start gap-3 px-4 py-3 sm:px-5">
              <span className="mt-px flex h-6 w-6 shrink-0 items-center justify-center">
                {team ? <TeamLogo team={team} size="md" className="h-6 w-6" /> : <Lightbulb size={18} className="text-amber-500" aria-hidden />}
              </span>
              <p className="min-w-0 text-sm leading-snug">{t(FACT_KEYS[f.key], f.params)}</p>
            </li>
          );
        })}
      </ul>
    </section>
  );
}

// ---------- next matches ----------

/** The fixture each club plays after this one. */
export function NextMatchesCard({ preview }: { preview: MatchPreview }) {
  const { t } = useI18n();
  const rows = (["home", "away"] as const).flatMap((side) => {
    const m = preview.nextMatches[side];
    return m ? [{ side, team: preview.teams[side], match: m }] : [];
  });
  if (rows.length === 0) return null;

  return (
    <section className="card overflow-hidden">
      <CardHeader title={t("preview.next")} icon={<CalendarClock size={16} />} />
      <ul className="divide-y divide-line">
        {rows.map((r) => (
          <li key={r.side}>
            <NextRow team={r.team} match={r.match} />
          </li>
        ))}
      </ul>
    </section>
  );
}

function NextRow({ team, match }: { team: TeamRef; match: MatchSummary }) {
  const { t, locale } = useI18n();
  const home = match.homeTeam.id === team.id;
  const opponent = home ? match.awayTeam : match.homeTeam;

  return (
    <Link to={`/match/${match.id}`} className="flex items-center gap-3 px-4 py-2.5 row-hover sm:px-5">
      <TeamLogo team={team} size="md" />
      <span className="min-w-0 flex-1">
        <span className="block truncate text-[11px] font-medium text-ink-3">{team.name}</span>
        <span className="flex min-w-0 items-center gap-1.5 text-sm font-semibold">
          <TeamLogo team={opponent} size="xs" />
          <span className="truncate">{opponent.name}</span>
          <span className={cn("shrink-0 rounded px-1 text-[10px] font-semibold uppercase", home ? "bg-brand/10 text-brand" : "bg-surface-3 text-ink-2")}>
            {t(home ? "preview.home" : "preview.away")}
          </span>
        </span>
      </span>
      <span className="shrink-0 text-right text-xs leading-tight">
        <span className="block font-semibold text-ink">{formatDate(match.kickoff, locale, { day: "numeric", month: "short" })}</span>
        <span className="block text-ink-3 tnum">{match.timeTbd ? t("date.tbd") : formatTime(match.kickoff, locale)}</span>
      </span>
    </Link>
  );
}
